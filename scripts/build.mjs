// `npm run build`: dist/plugin.js, the one file the editor loads (`build` in plugin.json).
// The esbuild command scm-js's plugins use, plus what this one needs: JSX, and React's
// production build (its development checks would otherwise come along). Unminified, so the
// bundle can be read. `--watch` rebuilds on every change.
import * as esbuild from "esbuild";

const options = {
  entryPoints: ["plugin.ts"],
  bundle: true,
  format: "esm",
  target: "es2022",
  platform: "browser",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "eof",
  outfile: "dist/plugin.js",
  banner: { js: "// Generated by npm run build - do not edit; the source is plugin.ts and src/." },
  logLevel: "info",
};

if (process.argv.includes("--watch")) await (await esbuild.context(options)).watch();
else await esbuild.build(options);
