// `npm run docs [ref]`: copy the editor's docs/triggers.md and docs/guide.md from
// scm-js/scm-js at a release tag into src/generated/docs.ts, which the read_docs tool
// searches. A module rather than the Markdown files, because an editor that compiles this
// plugin in (scripts/vendor-plugins.mjs in scm-js) takes .ts files only. Run it again when
// the editor ships a release whose docs changed; the ref is recorded in the file.
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";

const ref = process.argv[2] ?? "v0.13.3";
const files = { TRIGGERS_MD: "docs/triggers.md", GUIDE_MD: "docs/guide.md" };

const parts = [];
const sums = [];
for (const [name, path] of Object.entries(files)) {
  const url = `https://raw.githubusercontent.com/scm-js/scm-js/${ref}/${path}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const text = (await res.text()).replace(/\r\n/g, "\n");
  sums.push(`${path} sha256 ${createHash("sha256").update(text).digest("hex").slice(0, 16)}`);
  parts.push(`export const ${name}: string = ${JSON.stringify(text)};`);
}

const header = [
  "// Generated by `npm run docs` - do not edit. The scmJS editor's documentation, which the",
  "// read_docs tool searches, copied from github.com/scm-js/scm-js (MIT, copyright scmJS):",
  `// ${ref}, ${sums.join(", ")}.`,
  `export const DOCS_REF = ${JSON.stringify(ref)};`,
];
await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(new URL("../src/generated/docs.ts", import.meta.url), `${header.join("\n")}\n${parts.join("\n")}\n`);
console.log(`src/generated/docs.ts from scm-js/scm-js@${ref}: ${sums.join(", ")}`);
